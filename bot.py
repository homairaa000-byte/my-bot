data = {}

# =========================
# أوامر
# =========================

@bot.message_handler(commands=['start'])
def start(message):
    bot.send_message(message.chat.id, build_list(), reply_markup=menu())

@bot.message_handler(commands=['rules'])
def rules(message):
    bot.send_message(message.chat.id, RULES_TEXT)

@bot.message_handler(commands=['schedule'])
def schedule(message):
    bot.send_message(message.chat.id, SCHEDULE_TEXT)

@bot.message_handler(commands=['help'])
def help_cmd(message):
    bot.send_message(message.chat.id, HELP_TEXT)

# =========================
# بناء القائمة
# =========================

def build_list():
    text = "📌 قائمة التسجيل:\n\n"
    if not data:
        return text + "لا يوجد تسجيلات"
    for uid, name in data.items():
        text += f"- {name}\n"
    return text

# =========================
# الأزرار
# =========================

@bot.callback_query_handler(func=lambda call: True)
def handle(call):
    uid = call.from_user.id
    name = call.from_user.full_name

    if call.data == "register":
        data[uid] = name

    elif call.data == "remove":
        data.pop(uid, None)

    elif call.data == "read":
        pass

    elif call.data == "listener":
        data[uid] = name + " 🎧"

    elif call.data == "excused":
        data[uid] = name + " ⛔️"

    bot.edit_message_text(
        build_list(),
        call.message.chat.id,
        call.message.message_id,
        reply_markup=menu()
    )

# =========================
# الترحيب
# =========================

@bot.message_handler(content_types=["new_chat_members"])
def welcome(message):
    for u in message.new_chat_members:
        msg = bot.send_message(
            message.chat.id,
            f"أهلاً بكِ {u.first_name}\n\n{WELCOME_MESSAGE}"
        )
        threading.Thread(
            target=delete_after,
            args=(message.chat.id, msg.message_id, 300)
        ).start()

